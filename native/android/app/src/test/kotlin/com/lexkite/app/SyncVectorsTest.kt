/** Shared helpers: vectors come from native/shared/gen/vectors (test resources) and gen/contract.json – all generated from the web JS. */
object Vectors {
    fun load(name: String): JsonObject = Json.parseToJsonElement(javaClass.classLoader!!.getResource(name)!!.readText()).jsonObject
    val contract: JsonObject by lazy { Json.parseToJsonElement(File("../../shared/gen/contract.json").readText()).jsonObject }
    /** Library entries the vector generator used (web lexicon) – `lib` map in the vector, else none. */
    fun lexicon(v: JsonObject): Lexicon { val lib = (v["lib"] as? JsonObject) ?: (contract["x-lexkite"]?.jsonObject?.get("lib") as? JsonObject); return if (lib == null) Lexicon.NONE else Lexicon { lib[it] as? JsonObject } }
    fun doc(e: JsonElement?): SyncDoc = SyncDoc.from(e as JsonObject)
    /** Exact equality in canonical JSON (sorted keys, JS number formatting) – absent and null top-level fields are distinct. */
    fun same(msg: String, expect: JsonElement?, got: JsonElement?) = assertEquals(msg, SyncMerge.stable(expect), SyncMerge.stable(got))
    fun sameDoc(msg: String, expect: JsonObject, got: SyncDoc, only: Collection<String>? = null) {
        val g = got.toJson()
        for (k in only ?: expect.keys) same("$msg · $k", expect[k], g[k])
    }
}

/** C02 – offline + sync: the Kotlin merge reproduces the web merge exactly (vectors/sync.json generated by the REAL web/js/sync.js). */
class SyncVectorsTest {
    private val v = Vectors.load("sync.json")
    private val now = v["now"]!!.jsonPrimitive.long
    private val lex = Vectors.lexicon(v)
    private val nonComm = (v["nonCommutative"] as? JsonArray)?.map { it.jsonPrimitive.content }?.toSet() ?: emptySet()
    private fun sync(local: SyncDoc, remote: SyncDoc, at: Long) = SyncMerge.wire(SyncMerge.mergeWire(local, remote, at, lex), at, lex)

    @Test fun parity_C02() {
        val cases = v["merge"]!!.jsonArray
        assertTrue("merge vectors present", cases.size >= 10)
        for (c in cases) {
            val o = c.jsonObject; val name = o["name"]!!.jsonPrimitive.content
            val out = sync(Vectors.doc(o["local"]), Vectors.doc(o["remote"]), now)
            Vectors.sameDoc(name, o["out"]!!.jsonObject, out)
        }
    }

    @Test fun mergeIsCommutativeAndIdempotent() {
        for (c in v["merge"]!!.jsonArray) {
            val o = c.jsonObject; val name = o["name"]!!.jsonPrimitive.content
            val a = Vectors.doc(o["local"]); val b = Vectors.doc(o["remote"])
            val ab = sync(a, b, now)
            val keys = if (name in nonComm) listOf("cards", "deleted", "stats", "game") else listOf("cards", "deleted", "stats", "game", "settings", "settingsAt")
            Vectors.sameDoc("commutative: $name", sync(b, a, now).toJson(), ab, keys)
            Vectors.sameDoc("idempotent: $name", ab.toJson(), sync(ab, ab, now))
            Vectors.sameDoc("re-merge remote: $name", ab.toJson(), sync(ab, b, now), keys)
        }
    }

    /** Cross-client scenarios (web/iOS/Android/add-on): replay every step with the native ports, compare every client + the server. */
    @Test fun crossClientScenarios() {
        for (sc in v["scenarios"]!!.jsonArray) {
            val s = sc.jsonObject; val name = s["name"]!!.jsonPrimitive.content
            val empty = SyncDoc(emptyMap(), emptyMap(), SyncDoc.DEFAULT_STATS, null, Js.EMPTY, Js.ZERO)
            val clients = HashMap<String, SyncDoc>(); var server: SyncDoc? = null; var at = now
            fun cl(id: String) = clients.getOrPut(id) { empty }
            fun syncClient(id: String) { val c = cl(id); val merged = server?.let { SyncMerge.mergeWire(c, it, at, lex) } ?: c.copy(cards = WebCards.normalize(c.cards, at)); clients[id] = merged; server = SyncMerge.wire(merged, at, lex) }
            for (st in s["steps"]!!.jsonArray) {
                val x = st.jsonObject; val who = x["client"]!!.jsonPrimitive.content; at = x["at"]!!.jsonPrimitive.long
                when (x["op"]!!.jsonPrimitive.content) {
                    "edit", "offline_edit" -> clients[who] = edit(cl(who), x["card"]!!.jsonPrimitive.content, (x["patch"] as? JsonObject) ?: Js.EMPTY, at)
                    "delete" -> { val c = cl(who); val (cards, del) = WebCards.remove(WebCards.normalize(c.cards, at), c.deleted, x["card"]!!.jsonPrimitive.content, at); clients[who] = c.copy(cards = cards, deleted = SyncMerge.pruneDel(del, at)) }
                    "sync" -> if (who == "addon") {
                        // the web app on the same machine syncs; the bridge merges the add-on store in and hands the result back
                        val w = cl("web"); val a = cl("addon")
                        val del = LinkedHashMap(w.deleted); for ((k, t) in a.deleted) del[k] = Js.max(Js.or(del[k], Js.ZERO), t)
                        clients["web"] = w.copy(cards = WebCards.normalize(SyncMerge.mergeCards(WebCards.normalize(w.cards, at), a.cards, del), at), deleted = del, stats = SyncMerge.mergeStats(w.stats, a.stats ?: JsonObject(mapOf("days" to Js.EMPTY))))
                        syncClient("web")
                        val wn = clients.getValue("web"); clients["addon"] = a.copy(cards = wn.cards, deleted = wn.deleted, stats = wn.stats)
                    } else syncClient(who)
                    else -> error("unknown op in $name")
                }
            }
            val exp = s["expect"]!!.jsonObject
            for ((who, e) in exp) {
                val eo = e.jsonObject
                val got = if (who == "server") server!! else SyncMerge.wire(cl(who), at, lex)
                Vectors.sameDoc("$name · $who", eo, got, if (who == "addon") listOf("cards", "deleted", "stats") else null)
            }
        }
    }

    private fun edit(c: SyncDoc, key: String, patch: JsonObject, at: Long): SyncDoc {
        val m = Regex("^([a-z]{2,3}):(.*)$").find(key)
        val tl = m?.groupValues?.get(1) ?: "en"; val word = m?.groupValues?.get(2) ?: key
        var cards = WebCards.normalize(c.cards, at); var del = c.deleted
        if (cards[key] == null) {
            val lib = if (tl == "en") lex.entry(word.lowercase()) else null
            val entry = JsonObject(LinkedHashMap<String, JsonElement>(lib ?: Js.EMPTY).apply { put("word", JsonPrimitive(word)); if (tl != "en") put("tl", JsonPrimitive(tl)) })
            val r = WebCards.add(cards, del, entry, Js.EMPTY, at); cards = LinkedHashMap(r.first); del = r.second
        }
        val card = LinkedHashMap<String, JsonElement>(cards.getValue(key)); card.putAll(patch); card["mod"] = JsonPrimitive(at)
        return c.copy(cards = LinkedHashMap(cards).apply { put(key, JsonObject(card)) }, deleted = del)
    }

    /** D1 wire helpers + key rule match the contract (generated from web). */
    @Test fun contractBucketsKeysDefaults() {
        val x = Vectors.contract["x-lexkite"]!!.jsonObject
        for (b in x["d1"]!!.jsonObject["bucketVectors"]!!.jsonArray) assertEquals(b.toString(), b.jsonObject["bucket"]!!.jsonPrimitive.long.toInt(), SyncCodec.bucketOf(b.jsonObject["key"]!!.jsonPrimitive.content))
        for (k in x["keys"]!!.jsonArray) { val o = k.jsonObject
            assertEquals(o.toString(), o["key"]!!.jsonPrimitive.content, MigrationImport.cardKey(JsonObject(mapOf("word" to o["word"]!!, "tl" to o["tl"]!!)))) }
        val defaults = x["cardDefaults"]!!.jsonObject
        Vectors.same("Cards.make", defaults, WebCards.make(JsonObject(mapOf("word" to JsonPrimitive("x"))), defaults["added"]!!.jsonPrimitive.long))
        assertEquals(WebCards.LIB_FIELDS, x["libFields"]!!.jsonArray.map { it.jsonPrimitive.content })
    }

    @Test fun gzipBodyAndEnvelopeRoundTrip() {
        val json = Js.stringify(JsonObject(mapOf("a" to JsonPrimitive("x".repeat(500)))))
        assertEquals(json, SyncCodec.docText(SyncCodec.docBody(json)))
        val snap = JsonObject(mapOf("cards" to Js.EMPTY, "at" to JsonPrimitive(1)))
        Vectors.same("drive envelope", snap, SyncCodec.unpack(SyncCodec.pack(snap)))
        assertEquals("0:0", SyncCodec.hash(""))
        assertEquals("1e+21", Js.numStr(1e21)); assertEquals("1e-7", Js.numStr(1e-7)); assertEquals("0.1", Js.numStr(0.1)); assertEquals("123", Js.numStr(123.0))
    }
}
