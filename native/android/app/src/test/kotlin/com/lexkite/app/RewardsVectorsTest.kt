package com.lexkite.app

import com.lexkite.app.core.RewardRules
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.double
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/** RewardRules (core/RewardRules.kt) against vectors/rewards.json – generated by running the real web Game.xpFor / repCut (scripts/native/gen-rewards.mjs). */
class RewardsVectorsTest {
    private val v = Json.parseToJsonElement(javaClass.classLoader!!.getResource("rewards.json")!!.readText()).jsonObject

    private fun JsonObject.num(k: String): Double? = (this[k] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.double
    private fun JsonObject.flag(k: String): Boolean = (this[k] as? JsonPrimitive)?.let { p -> if (p is JsonNull) false else p.content.let { c -> c == "true" || (c.toDoubleOrNull() ?: 0.0) != 0.0 } } ?: false

    @Test fun constants() {
        val x = v.getValue("XPR").jsonObject
        fun i(k: String) = x.getValue(k).jsonPrimitive.int
        assertEquals(i("pick"), RewardRules.PICK); assertEquals(i("type"), RewardRules.TYPE); assertEquals(i("write"), RewardRules.WRITE); assertEquals(i("say"), RewardRules.SAY)
        assertEquals(i("hard"), RewardRules.HARD); assertEquals(i("set"), RewardRules.SET); assertEquals(i("exam"), RewardRules.EXAM); assertEquals(i("sec"), RewardRules.SEC)
        assertEquals(i("perfect"), RewardRules.PERFECT); assertEquals(i("min"), RewardRules.MIN); assertEquals(i("talk"), RewardRules.TALK); assertEquals(i("essay"), RewardRules.ESSAY)
        assertEquals(i("learn"), RewardRules.LEARN); assertEquals(i("day"), RewardRules.DAY); assertEquals(i("step"), RewardRules.STEP); assertEquals(i("great"), RewardRules.GREAT); assertEquals(i("pass"), RewardRules.PASS)
        assertEquals(i("cap"), RewardRules.CAP); assertEquals(i("game"), RewardRules.GAME)
        assertEquals(x.getValue("card").jsonArray.map { it.jsonPrimitive.int }, RewardRules.CARD.toList())
    }

    @Test fun xpForCases() {
        val cases = v.getValue("cases").jsonArray
        assertTrue(cases.size > 50)
        val bad = ArrayList<String>()
        for (c in cases) {
            val o = c.jsonObject; val kind = o.getValue("kind").jsonPrimitive.content; val a = o.getValue("args").jsonObject; val want = o.getValue("xp").jsonPrimitive.int
            val mode = (a["mode"] as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content
            val got = RewardRules.xp(kind, right = (a.num("right") ?: 0.0).toInt(), total = (a.num("total") ?: 0.0).toInt(), mode = mode, hard = a.flag("hard"),
                hints = (a.num("hints") ?: 0.0).toInt(), score = a.num("score"), paid = a.flag("paid"), words = a.num("words") ?: 0.0,
                sections = (a.num("sections") ?: 0.0).toInt(), isNew = a.flag("isNew"), again = a.flag("again"))
            if (got != want) bad.add("$kind $a: $got != $want")
        }
        assertTrue(bad.joinToString(" | "), bad.isEmpty())
    }

    @Test fun repCut() {
        val rows = v.getValue("repCut").jsonArray
        assertTrue(rows.size > 10)
        for (r in rows) { val o = r.jsonObject; assertEquals("repCut(${o["xp"]}, ${o["count"]})", o.getValue("out").jsonPrimitive.int, RewardRules.repCut(o.getValue("xp").jsonPrimitive.int, o.getValue("count").jsonPrimitive.int)) }
    }
}
