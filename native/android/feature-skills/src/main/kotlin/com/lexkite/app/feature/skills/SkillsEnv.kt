/**
 * Everything the listening + reading screens need from the app graph: the vocabulary env (store, audio, mistakes, rewards), the word env (dictionary, cards, speech)
 * and the content pack (parts, passages, word tables). [loadContent] is injected by :app; null = no pack yet (the screens show their empty state).
 */
class SkillsEnv(val vocab: VocabEnv, val word: WordEnv, val learnLang: String, private val loadContent: suspend () -> SkillsContent?) {
    @Volatile private var memo: SkillsContent? = null
    suspend fun content(): SkillsContent? = memo ?: loadContent()?.also { memo = it }
    val now: Long get() = vocab.now()

    /** The web's localStorage keys (vb.listenT, vb.readLv): device only, never synced. */
    suspend fun kv(k: String): String? = (vocab.store.get(k) as? JsonPrimitive)?.content
    suspend fun putKv(k: String, v: String) = vocab.store.put(mapOf(k to JsonPrimitive(v)), local = false)
    /** One synced setting (listenRate, dictMode, dictAuto, hl). */
    suspend fun setSetting(k: String, v: JsonElement) { val t = now; vocab.store.mutate { d -> d.copy(settings = JsonObject(Js.spread(d.settings) + (k to v)), settingsAt = JsonPrimitive(t)) } }
    fun voicesFor(accent: String): List<String> = vocab.audio.voiceNames(accent)

    /** The dictionary / word-book port of the popup (cards and library index are snapshots taken when the screen opens). */
    suspend fun port(): WordPort {
        val index = runCatching { word.index() }.getOrDefault(emptyMap())
        val cards0 = word.cards().keys
        return object : WordPort {
            private var cards = cards0
            override suspend fun quick(w: String) = word.dict().quick(w)
            override suspend fun lookup(w: String, examples: Boolean, image: Boolean) = word.dict().lookup(w, image = image, examples = examples)
            override suspend fun translateVi(s: String) = word.dict().translateVi(s)
            override suspend fun translateTo(s: String, lang: String) = word.dict().translateTo(s, lang)
            override fun inDeck(w: String) = CardMath.keyOf(w) in cards
            override suspend fun addWord(entry: JsonObject, context: JsonObject?, silent: Boolean) { word.addWord(entry, context, silent); cards = word.cards().keys }
            override fun libraryEntry(w: String) = index[w]
        }
    }

    companion object {
        /**
         * The content pack https://lexkite.com/data/skills-pack.json (generated by scripts/native/gen.mjs, `v` = content hash): `{v, schema, listening[40], readings[57], lexis, consts}` –
         * listening/readings/lexis in the shape of vectors/skills.json `data`, consts = band table, Kokoro pools, dictation stopwords (installed by [SkillsContent.parse]).
         * Cached on disk: a good download replaces the cache, a failed/invalid one falls back to it; null = no pack anywhere (the hub shows its empty state).
         */
        suspend fun fetchPack(http: Http, cacheDir: File, url: String = PACK_URL, starter: () -> String? = { null }): SkillsContent? = withContext(Dispatchers.IO) {
            val f = File(cacheDir, "skills-pack.json")
            fun parse(t: String) = runCatching { SkillsContent.parse(Json.parseToJsonElement(t) as JsonObject).takeIf { it.listening.isNotEmpty() } }.getOrNull()
            val r = runCatching { http.send(Http.Req("GET", url)) }.getOrNull()
            val fresh = if (r != null && r.ok) parse(r.text)?.also { runCatching { f.parentFile?.mkdirs(); f.writeText(r.text) } } else null
            fresh ?: (if (f.exists()) runCatching { f.readText() }.getOrNull()?.let(::parse) else null) ?: runCatching { starter() }.getOrNull()?.let(::parse) // bundled 2-test starter: the hub is never empty offline
        }
        const val PACK_URL = "https://lexkite.com/data/skills-pack.json"
    }
}

/** [PlayerIO] over the app audio: whole-line Kokoro clips through [LkAudio.playKey], the device-voice cast through [LkAudio.speakCast]. */
class LkPlayerIO(private val audio: LkAudio, private val scope: CoroutineScope, private val onToast: (String) -> Unit = {}) : PlayerIO {
    override val canPlay get() = true
    override val canSpeak get() = true
    private val pending = ArrayList<CompletableDeferred<Unit>>()
    private var startHook: (() -> Unit)? = null; private var firstStarted = false

    override suspend fun playClip(key: String, rate: Double, onPlaying: () -> Unit): Clip = audio.playKey(key, rate.toFloat(), onPlaying)
    override fun preload(key: String) { scope.launch { audio.resolve(key) } }
    override fun queue(u: Utter) {
        val d = CompletableDeferred<Unit>(); val first = pending.isEmpty(); pending.add(d)
        audio.speakCast(u.text, u.voice, u.lang, u.pitch.toFloat(), u.rate.toFloat(), object : TtsCallback {
            override fun onStart() { if (first) { val h = startHook; if (h != null) h() else firstStarted = true } }
            override fun onEnd() { d.complete(Unit) }
            override fun onError() { d.complete(Unit) }
        })
    }
    override suspend fun awaitSpeech(onStart: () -> Unit) {
        startHook = onStart; if (firstStarted) { firstStarted = false; onStart() }
        try { pending.lastOrNull()?.await() } finally { pending.clear(); startHook = null; firstStarted = false }
    }
    override suspend fun delay(ms: Long) = kotlinx.coroutines.delay(ms)
    override fun stopAll() { audio.stop(); pending.forEach { it.complete(Unit) }; pending.clear() }
    override fun toast(key: String) = onToast(key)
}
