package com.lexkite.app.core.sync

import com.lexkite.app.core.migration.MigrationImport
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject

/**
 * Onboarding starter deck (C17), same as web: at the end of setup every pack adds the words of the first 3 topics of its exam
 * (web/js/onboard.js `topicsFor(ex).slice(0, 3)` → `D.addWord` = `Core.Cards.add`), skipping words already in the deck.
 * The word entries are the bundled pack `content-pack/starter.json` (generated by scripts/native/starter.mjs from the web data, never typed here);
 * the expected result is vectors/starter-deck.json, produced by running the real web `Cards.make`.
 */
object StarterDeck {
    class Pack(val byExam: Map<String, List<String>>, val topics: Map<String, List<JsonObject>>)

    fun parse(text: String): Pack {
        val o = Json.parseToJsonElement(text).jsonObject
        return Pack(
            (o["byExam"]?.jsonObject ?: JsonObject(emptyMap())).mapValues { (_, v) -> v.jsonArray.map { (it as JsonPrimitive).content } },
            (o["topics"]?.jsonObject ?: JsonObject(emptyMap())).mapValues { (_, v) -> v.jsonArray.map { it.jsonObject } },
        )
    }

    /** Cards in web insertion order (topic by topic, first occurrence of a word wins), each with `mod = now` like `Cards._add`. */
    fun cards(exam: String, pack: Pack, now: Long): List<Pair<String, JsonObject>> {
        val seen = HashSet<String>(); val out = ArrayList<Pair<String, JsonObject>>()
        for (id in pack.byExam[exam].orEmpty()) for (e in pack.topics[id].orEmpty()) {
            val key = MigrationImport.cardKey(e) ?: continue
            if (!seen.add(key)) continue
            out.add(key to JsonObject(LinkedHashMap(WebCards.make(e, now)).apply { put("mod", JsonPrimitive(now)) }))
        }
        return out
    }

    /** Adds the starter deck; words already there stay untouched (web `if (!D.inDeck(w.word))`), a tombstone for an added word is cleared. */
    fun add(doc: SyncDoc, exam: String, pack: Pack, now: Long): SyncDoc {
        val cards = LinkedHashMap(doc.cards); val deleted = LinkedHashMap(doc.deleted)
        for ((key, card) in cards(exam, pack, now)) if (key !in cards) { cards[key] = card; deleted.remove(key) }
        return doc.copy(cards = cards, deleted = deleted)
    }
}
