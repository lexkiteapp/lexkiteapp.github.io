/* Native P12 – Learn from YouTube (#/watch). Reference = the REAL web/js/watch-topics.js + web/js/watch.js run in node:vm.
 * Outputs: content-pack/watch-topics.json (topics, levels, filters, query tails – bundled in both apps) and vectors/watch.json
 * (ytParse on every link form, fmt, buildQ per filter, forYou ranking, result filter by duration, player RATES).
 * Native screens: hub (paste/search/filters/topics/continue/for you) + player (official YouTube IFrame player in a web view,
 * A-B loop by seekTo, speed, back 5 s, time notes, look up + save word). docs/specs/video-learn.md. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = p => path.join(ROOT, p);
export const TOPICS_PATH = 'native/shared/gen/content-pack/watch-topics.json';

function load() {
  const store = {};
  const app = { state: { cards: {}, settings: {} }, routes: {}, view: {}, exam: () => 'general' };
  const sb = { console, URL, URLSearchParams, Promise, Math, Set, Date, JSON, RegExp, String, Number,
    UI: { $: () => null, $$: () => [], esc: s => String(s), toast: () => {} }, App: app, location: { protocol: 'https:', hostname: 'lexkite.com' },
    localStorage: { getItem: k => (k in store ? store[k] : null), setItem: (k, v) => { store[k] = String(v); }, removeItem: k => { delete store[k]; } } };
  sb.window = sb; sb.globalThis = sb; vm.createContext(sb);
  for (const f of ['web/js/watch-topics.js', 'web/js/watch.js']) vm.runInContext(fs.readFileSync(R(f), 'utf8'), sb, { filename: f });
  const src = fs.readFileSync(R('web/js/watch.js'), 'utf8');
  const RATES = JSON.parse(/const RATES = (\[[^\]]+\])/.exec(src)[1]);
  return { W: sb.WatchTopics, X: sb.Watch, app, store, RATES };
}

export function watchTopics() {
  const { W } = load();
  const lvQ = [1, 2, 3, 4, 5, 6].map(n => W.LV_Q(n));
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-watch.mjs from web/js/watch-topics.js. name/desc/filter labels are Vietnamese i18n keys (native/shared/strings.json watch.*); lv = CEFR 1..6 range; goals match the exam goal (all = any); q[0] = main query; ch = public channel ids (RSS feed); kw = RSS title filter; vocab = words that boost "for you". lvQ[n-1] = query tail for level n.',
    levels: W.LEVELS, filters: W.FILTERS, accQ: W.ACC_Q, paceQ: W.PACE_Q, lvQ, topics: W.TOPICS }, null, 1) + '\n';
}

export function watchVectors() {
  const { W, X, app, store, RATES } = load();
  const links = ['dQw4w9WgXcQ', 'https://www.youtube.com/watch?v=dQw4w9WgXcQ', 'youtube.com/watch?v=dQw4w9WgXcQ&t=1m30s', 'https://youtu.be/dQw4w9WgXcQ?t=95', 'https://m.youtube.com/watch?v=dQw4w9WgXcQ&start=42',
    'https://music.youtube.com/watch?v=dQw4w9WgXcQ', 'https://www.youtube.com/shorts/abcdefghijk', 'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ?start=10', 'https://www.youtube.com/live/abcdefghijk', 'https://www.youtube.com/watch?v=dQw4w9WgXcQ#t=2h3m4s',
    'https://youtu.be/dQw4w9WgXcQ?t=1h', 'https://vimeo.com/123', 'https://www.youtube.com/watch?v=short', 'not a link', '', 'https://evil.com/watch?v=dQw4w9WgXcQ', 'https://www.youtube.com/channel/UCsooa4yRKGN', '  https://youtu.be/dQw4w9WgXcQ  ', 'https://youtu.be/dQw4w9WgXcQ?t=abc'];
  const parse = links.map(s => ({ in: s, out: X.ytParse(s) ? { ...X.ytParse(s) } : null }));
  const fmt = [-3, 0, 5, 59, 60, 61, 599, 3599, 3600, 3661, 36000, 12.7].map(s => ({ s, out: X.fmt(s) }));
  const setPlacement = p => { app.state.settings = p ? { placement: p } : {}; };
  const buildQ = [];
  for (const [place, f] of [[null, {}], [null, { lv: 1 }], [null, { lv: 3, acc: 'uk' }], [null, { lv: 5, pace: 'slow' }], [{ vCefr: 'b2' }, { acc: 'au', pace: 'natural' }], [{ band: 7.5 }, {}], [{ band: 5 }, {}], [{ gCefr: 'C2' }, {}]])
    for (const base of ['everyday english conversation', 'english for beginners easy']) { setPlacement(place); buildQ.push({ base, placement: place, f, out: X.buildQ(base, { lv: 0, dur: '', acc: '', pace: '', cc: true, ...f }) }); }
  const forYou = [];
  const cases = [
    { goal: 'general', placement: null, words: [], lv: 0, history: [] },
    { goal: 'ielts', placement: { band: 7 }, words: ['climate', 'energy', 'research'], lv: 0, history: [] },
    { goal: 'toeic', placement: { vCefr: 'A2' }, words: ['meeting', 'invoice'], lv: 0, history: [{ id: 'x', topic: 'work' }] },
    { goal: 'toefl', placement: null, words: [], lv: 6, history: [] },
    { goal: 'general', placement: null, words: ['hello', 'shop', 'buy', 'airport'], lv: 1, history: [{ id: 'a', topic: 'travel' }, { id: 'b', topic: 'travel' }] },
  ];
  for (const c of cases) {
    app.exam = () => c.goal; setPlacement(c.placement); app.state.cards = Object.fromEntries(c.words.map(w => [w, {}]));
    for (const k of Object.keys(store)) delete store[k];
    store['wt.f'] = JSON.stringify({ lv: c.lv }); store['wt.h'] = JSON.stringify(c.history);
    forYou.push({ ...c, out: X.forYou().map(t => t.id) });
  }
  // result list rule of run(): search items first then feed, unique valid ids, duration filter (sec missing = kept), max 24
  const durRule = { short: 'sec < 240', medium: '240 <= sec <= 1200', long: 'sec > 1200', max: 24 };
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-watch.mjs from web/js/watch.js (Watch.ytParse/fmt/buildQ/forYou). buildQ uses the level from f.lv or, when 0, myLevel(placement): CEFR vCefr|gCefr → 1..6, else band ≥7→5, ≥5.5→4, ≥4.5→3, else 2; no placement → 2. forYou: score = +3 level in range else −2, +3 goal match, −4 when the topic has neither the goal nor "all", +1 per deck word in topic vocab, +1 per topic hit in the 10 newest history rows; keep score > 0, sort desc (stable), top 6.',
    rates: RATES, parse, fmt, buildQ, forYou, durRule }, null, 1) + '\n';
}

