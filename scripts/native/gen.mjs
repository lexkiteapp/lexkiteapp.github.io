#!/usr/bin/env node
/* Native apps – ONE-SOURCE generator (docs/specs/native-apps.md §3).
 * Everything the SwiftUI / Compose apps share with web is GENERATED here from repo sources; nothing is copied by hand:
 *   tokens   brand/stitch/tokens.dtcg.json (Stitch "Lexkite Kit")      → Tokens.swift + Tokens.kt (light B / dark A)
 *   strings  native/shared/strings.json (id → Vietnamese key) resolved in web i18n (en/*.js + i18n/ui/<lang>) → <lang>.json ×15 + L10nKey.swift/.kt
 *   frame    web/js/st/v2/runtime.js TABS (5 tabs Today/Vocab/Skills/Tests/Me)  → frame.json
 *   scoring  web/js/core.js (FSRS-5 SRS) + web/js/lesson/engine.js (norm/check) run in Node → srs-params.json + conformance vectors
 * Usage: node scripts/native/gen.mjs          (write)
 *        node scripts/native/gen.mjs --check  (CI drift gate: exit 1 if any generated file differs or a string is missing)
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = p => path.join(ROOT, p);
const CHECK = process.argv.includes('--check');
const HEAD = src => `// GENERATED by scripts/native/gen.mjs from ${src} – do not edit by hand.\n`;
const out = new Map(); // relPath → content
const put = (rel, s) => out.set(rel, s.endsWith('\n') ? s : s + '\n');
const json = o => JSON.stringify(o, null, 2) + '\n';

const IOS = 'native/ios/LexkiteKit';
const AND = 'native/android/app/src';
const SHARED = 'native/shared/gen';

// ---------- tokens ----------
const dtcg = JSON.parse(fs.readFileSync(R('brand/stitch/tokens.dtcg.json'), 'utf8'));
const camel = s => s.replace(/[-_ ]+([a-z0-9])/gi, (_, c) => c.toUpperCase()).replace(/^[A-Z]/, c => c.toLowerCase());
const ident = s => { const c = camel(s); return /^[0-9]/.test(c) ? '_' + c : c === 'default' ? 'base' : c; };
const hex = h => { h = String(h).replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join(''); if (!/^[0-9a-f]{6}([0-9a-f]{2})?$/i.test(h)) throw new Error('bad colour ' + h); return h.length === 6 ? h + 'FF' : h; };
const px = v => { const m = String(v).match(/^(-?[\d.]+)(px|rem|em)?$/); if (!m) throw new Error('bad dimension ' + v); return m[2] === 'rem' || m[2] === 'em' ? +m[1] * 16 : +m[1]; };
const colors = Object.entries(dtcg.color).filter(([, v]) => v.$type === 'color').map(([k, v]) => {
  const light = v.$extensions?.['com.lexkite.mode']?.light ?? v.$value;
  return { k: ident(k), dark: hex(v.$value), light: hex(light) };
});
const dims = group => Object.entries(dtcg[group] || {}).map(([k, v]) => ({ k: ident(k), v: px(v.$value) }));
const spacing = dims('spacing'), radius = dims('radius');
const type = Object.entries(dtcg.typography).map(([k, v]) => ({ k: ident(k), size: px(v.$value.fontSize), line: px(v.$value.lineHeight), weight: +v.$value.fontWeight, track: parseFloat(v.$value.letterSpacing) || 0 }));
const fade = parseInt(dtcg.motion.fade.$value, 10), ease = dtcg.motion.ease.$value;
const n = v => (Number.isInteger(v) ? v.toFixed(1) : String(v));

put(`${IOS}/Sources/LKDesign/Generated/Tokens.swift`, HEAD('brand/stitch/tokens.dtcg.json') + `import SwiftUI

/// Lexkite Kit colour roles. light = "Bright Day" (B), dark = "Tactile Night" (A); resolved by the current colour scheme.
public enum LKColor {
${colors.map(c => `    public static let ${c.k} = LKDynamicColor(light: 0x${c.light}, dark: 0x${c.dark})`).join('\n')}
}

public enum LKSpacing {
${spacing.map(d => `    public static let ${d.k}: CGFloat = ${n(d.v)}`).join('\n')}
}

public enum LKRadius {
${radius.map(d => `    public static let ${d.k}: CGFloat = ${n(Math.min(d.v, 9999))}`).join('\n')}
}

public enum LKType {
${type.map(t => `    public static let ${t.k} = LKTextStyle(size: ${n(t.size)}, lineHeight: ${n(t.line)}, weight: ${t.weight}, tracking: ${n(t.track)})`).join('\n')}
}

public enum LKMotion {
    public static let fadeMs = ${fade}
    public static let ease: (Double, Double, Double, Double) = (${ease.map(n).join(', ')})
}
`);

put(`${AND}/main/kotlin/com/lexkite/app/design/generated/Tokens.kt`, HEAD('brand/stitch/tokens.dtcg.json') + `package com.lexkite.app.design.generated

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** Lexkite Kit colour roles: light = "Bright Day" (B), dark = "Tactile Night" (A). */
object LKColorLight {
${colors.map(c => `    val ${c.k} = Color(0x${c.light.slice(6)}${c.light.slice(0, 6)})`).join('\n')}
}

object LKColorDark {
${colors.map(c => `    val ${c.k} = Color(0x${c.dark.slice(6)}${c.dark.slice(0, 6)})`).join('\n')}
}

object LKSpacing {
${spacing.map(d => `    val ${d.k} = ${n(d.v)}.dp`).join('\n')}
}

object LKRadius {
${radius.map(d => `    val ${d.k} = ${n(Math.min(d.v, 9999))}.dp`).join('\n')}
}

data class LKTextStyle(val size: androidx.compose.ui.unit.TextUnit, val lineHeight: androidx.compose.ui.unit.TextUnit, val weight: Int, val trackingEm: Float)

object LKType {
${type.map(t => `    val ${t.k} = LKTextStyle(${n(t.size)}.sp, ${n(t.line)}.sp, ${t.weight}, ${n(t.track)}f)`).join('\n')}
}

object LKMotion {
    const val FADE_MS = ${fade}
    val EASE = floatArrayOf(${ease.map(v => n(v) + 'f').join(', ')})
}
`);

// ---------- strings (15 languages) ----------
const LANGS = ['vi', 'en', ...fs.readFileSync(R('scripts/i18n-langs.txt'), 'utf8').split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#'))];
if (LANGS.length !== 15) throw new Error(`expected 15 UI languages, got ${LANGS.length}`);
const sb = { console }; sb.self = sb; sb.globalThis = sb; vm.createContext(sb);
const load = f => vm.runInContext(fs.readFileSync(R(f), 'utf8'), sb, { filename: f });
load('web/js/i18n/en.js');
fs.readdirSync(R('web/js/i18n/en')).filter(f => f.endsWith('.js')).sort().forEach(f => load(`web/js/i18n/en/${f}`)); // lazy groups are not all packed into en.js
for (const l of LANGS.slice(2)) {
  load(`i18n/ui/${l}.js`);
  const dir = R(`i18n/ui/${l}`);
  if (fs.existsSync(dir)) fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort().forEach(f => load(`i18n/ui/${l}/${f}`));
}
const D = sb.I18N_DICT;
const ids = Object.entries(JSON.parse(fs.readFileSync(R('native/shared/strings.json'), 'utf8'))).filter(([k]) => !k.startsWith('_'));
const missing = [];
for (const l of LANGS) {
  const o = {};
  for (const [id, vi] of ids) {
    const v = l === 'vi' ? vi : D[l] && D[l][vi];
    if (!v) missing.push(`${l}:${id}`); else o[id] = v;
  }
  const s = json(o);
  put(`${SHARED}/strings/${l}.json`, s);
  put(`${IOS}/Sources/LKStrings/Resources/strings/${l}.json`, s);
}
const keyId = id => ident(id.replace(/\./g, '-'));
put(`${IOS}/Sources/LKStrings/Generated/L10nKey.swift`, HEAD('native/shared/strings.json') + `/// Typed string IDs. Text comes from the generated per-language JSON (15 languages), never from literals in views.
public enum L10nKey: String, CaseIterable, Sendable {
${ids.map(([id]) => `    case ${keyId(id)} = "${id}"`).join('\n')}
}

public enum L10nLangs {
    public static let all = [${LANGS.map(l => `"${l}"`).join(', ')}]
    public static let rtl: Set<String> = ["ar"]
}
`);
put(`${AND}/main/kotlin/com/lexkite/app/i18n/generated/L10nKey.kt`, HEAD('native/shared/strings.json') + `package com.lexkite.app.i18n.generated

/** Typed string IDs. Text comes from the generated per-language JSON (15 languages), never from literals in composables. */
enum class L10nKey(val id: String) {
${ids.map(([id]) => `    ${keyId(id)}("${id}")`).join(',\n')};
}

object L10nLangs {
    val ALL = listOf(${LANGS.map(l => `"${l}"`).join(', ')})
    val RTL = setOf("ar")
}
`);

// ---------- app frame (5 tabs) ----------
const rt = fs.readFileSync(R('web/js/st/v2/runtime.js'), 'utf8');
const tm = rt.match(/const TABS = (\[[^;]+\]);/);
if (!tm) throw new Error('TABS not found in web/js/st/v2/runtime.js');
const TABS = JSON.parse(tm[1].replace(/'/g, '"'));
// Material Symbols (web, Stitch) → closest native glyph until M1 bundles the same Material Symbols subset font on both platforms
const ICONS = { home: ['house.fill', 'Home'], menu_book: ['book.fill', 'MenuBook'], target: ['target', 'TrackChanges'], flag: ['flag.fill', 'Flag'], person: ['person.fill', 'Person'] };
const tabIds = { 'Hôm nay': 'tab.today', 'Từ vựng': 'tab.vocab', 'Kỹ năng': 'tab.skills', 'Thi': 'tab.tests', 'Tôi': 'tab.me' };
const frame = { width: 390, gutter: 16, minTap: 44, tabs: TABS.map(([k, href, icon, vi]) => {
  const id = tabIds[vi]; if (!id) throw new Error(`tab label "${vi}" has no native string id`);
  const ic = ICONS[icon]; if (!ic) throw new Error(`no native glyph for Material Symbol "${icon}" (add it to ICONS)`);
  return { k, route: href.replace('#/', ''), icon, sf: ic[0], compose: ic[1], label: id };
}) };
if (frame.tabs.length !== 5) throw new Error('app frame must have exactly 5 tabs');
for (const p of [SHARED, `${IOS}/Sources/LKDesign/Resources`]) put(`${p}/frame.json`, json(frame));

// ---------- scoring: params + conformance vectors (reference = the web JS engine) ----------
process.env.TZ = 'UTC'; // vectors are computed in UTC; native tests run with TimeZone UTC
const core = fs.readFileSync(R('web/js/core.js'), 'utf8');
const wm = core.match(/const W = (\[[^\]]+\]);/), dm = core.match(/const DECAY = ([-\d.]+), FACTOR = ([\d/ ]+), MAX_IVL = (\d+);/);
if (!wm || !dm) throw new Error('FSRS constants not found in web/js/core.js');
const params = { W: JSON.parse(wm[1]), DECAY: +dm[1], FACTOR: eval(dm[2]), MAX_IVL: +dm[3], retentionTarget: 0.9, learnStepsMin: { again: 1, hard: [6, 10], good: 10 }, dayRolloverHour: 4 };
const cb = { console, Date, Math, navigator: {}, location: { hostname: 'native-gen' }, setTimeout, clearTimeout }; cb.self = cb; cb.globalThis = cb; vm.createContext(cb);
vm.runInContext(core, cb, { filename: 'web/js/core.js' });
vm.runInContext(fs.readFileSync(R('web/js/lesson/engine.js'), 'utf8'), cb, { filename: 'web/js/lesson/engine.js' });
const { SRS } = cb.Core, LE = cb.LessonEngine;
if (SRS.retentionTarget !== params.retentionTarget) throw new Error('retentionTarget drifted');
const T0 = Date.UTC(2026, 0, 5, 9, 0, 0), H = 36e5, DAY = 864e5;
const seqs = [[2, 2, 2, 2, 2], [0, 0, 2, 2, 3], [3, 3, 3], [1, 1, 2, 1, 2, 0, 2, 2], [2, 2, 2, 0, 2, 2, 1, 3], [3, 0, 3, 3, 2], [2, 1, 2, 2, 2, 2, 2, 2, 2, 2]];
const fsrs = seqs.map((grades, si) => {
  let s = SRS.newState(); s.due = T0; let now = T0;
  const steps = grades.map((g, i) => {
    s = SRS.review(JSON.parse(JSON.stringify(s)), g, now, true);
    const st = { grade: g, now, S: s.S, D: s.D, reps: s.reps, lapses: s.lapses, step: s.step, interval: s.interval, due: s.due };
    now = Math.max(now + 10 * 6e4, s.due) + (si + i) * H; // review a little after it is due
    return st;
  });
  return { start: T0, grades, steps };
});
const ansCases = [
  ['Consider', 'consider'], ['  well-being ', 'well being'], ['don’t', "don't"], ['It\'s fine.', 'its fine'], ['café', 'caf'], ['Hello, world!', 'hello world'],
  ['co-operate', 'co operate'], ['A  B\tC', 'a b c'], ['naïve', 'nave'], ['“quoted”', 'quoted'], ['İstanbul', 'istanbul'], ['STRASSE', 'strasse'], ['x', 'y'], ['', ''],
];
const answer = {
  norm: ansCases.flatMap(([a, b]) => [a, b]).map(s => ({ in: s, out: LE.norm(s) })),
  check: [
    [{ type: 'type', answer: 'consider' }, 'Consider '], [{ type: 'type', answer: 'consider' }, 'considr'], [{ type: 'gap', answer: "don't" }, 'don’t'],
    [{ type: 'build', answer: 'I like green tea' }, ['I', 'like', 'green', 'tea']], [{ type: 'build', answer: 'I like green tea' }, ['I', 'green', 'like', 'tea']],
    [{ type: 'tr', answer: 'See you soon' }, 'see you soon!'], [{ type: 'say', answer: 'hello' }, 0.7], [{ type: 'say', answer: 'hello' }, 0.69],
    [{ type: 'say', answer: 'hello' }, 'Hello'], [{ type: 'pic', answer: 'apple' }, 'apple'], [{ type: 'pic', answer: 'apple', choice: true }, 'Apple'], [{ type: 'match', answer: '' }, true], [{ type: 'match', answer: '' }, false],
  ].map(([it, ans]) => ({ item: it, ans, ok: LE.check(it, ans) })),
};
const vec = { _doc: 'Reference outputs of web/js/core.js SRS.review(noFuzz) and web/js/lesson/engine.js norm/check, TZ=UTC. Swift + Kotlin ports must match exactly (S/D to 1e-9).', params, fsrs, answer };
put(`${SHARED}/vectors/scoring.json`, json(vec));
put(`${IOS}/Tests/LKCoreTests/Resources/scoring.json`, json(vec));

// ---------- write / check ----------
let drift = 0;
for (const [rel, s] of out) {
  const f = R(rel), cur = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
  if (cur === s) continue;
  if (CHECK) { drift++; console.error(`DRIFT ${rel} (run: node scripts/native/gen.mjs)`); }
  else { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, s); console.log('wrote', rel); }
}
if (missing.length) { console.error(`MISSING translations (${missing.length}): ${missing.slice(0, 20).join(', ')} – add them through the web i18n pipeline, never in native code`); process.exit(1); }
if (drift) process.exit(1);
console.log(`native gen ${CHECK ? 'check' : 'write'} OK: ${colors.length} colours, ${ids.length} strings × ${LANGS.length} langs, ${frame.tabs.length} tabs, ${fsrs.length} FSRS seqs, ${answer.norm.length + answer.check.length} answer vectors`);
