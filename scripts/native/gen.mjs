const camel = s => s.replace(/[-_ ]+([a-z0-9])/gi, (_, c) => c.toUpperCase()).replace(/^[A-Z]/, c => c.toLowerCase());
const ident = s => { const c = camel(s); return /^[0-9]/.test(c) ? '_' + c : c === 'default' ? 'base' : c; };
const hex = h => { h = String(h).replace('#', ''); if (h.length === 3) h = h.split('').map(c => c + c).join(''); if (!/^[0-9a-f]{6}([0-9a-f]{2})?$/i.test(h)) throw new Error('bad colour ' + h); return h.length === 6 ? h + 'FF' : h; };
const px = v => { const m = String(v).match(/^(-?[\d.]+)(px|rem|em)?$/); if (!m) throw new Error('bad dimension ' + v); return m[2] === 'rem' || m[2] === 'em' ? +m[1] * 16 : +m[1]; };
const colors = Object.entries(dtcg.color).filter(([, v]) => v.$type === 'color').map(([k, v]) => {
  const light = v.$extensions?.['com.lexkite.mode']?.light ?? v.$value;
  return { k: ident(k), dark: hex(v.$value), light: hex(light) };
});
const dims = group => Object.entries(dtcg[group] || {}).map(([k, v]) => ({ k: ident(k), v: px(v.$value) }));
const spacing = dims('spacing'), radius = dims('radius');
const type = Object.entries(dtcg.typography).map(([k, v]) => ({ k: ident(k), size: px(v.$value.fontSize), line: px(v.$value.lineHeight), weight: +v.$value.fontWeight, track: parseFloat(v.$value.letterSpacing) || 0 }));
const fade = parseInt(dtcg.motion.fade.$value, 10), ease = dtcg.motion.ease.$value;
const n = v => (Number.isInteger(v) ? v.toFixed(1) : String(v));

