/* Native – "Phiên dịch / Interpreter" data + conformance vectors (#/interpret, docs/INTERPRET.md).
 * ONE source with the web: web/cpack/interpret/phrases.js (22 phrases × 15 languages, written by people) → content-pack/interpret-phrases.json (+ iOS LKStore resource);
 * web/cpack/interpret/core.js (language ↔ voice locale, who spoke, history, key words, review cards) runs in node:vm on a localStorage stub → vectors/interpret.json.
 * Microphone, translation, language detection and speech are PLATFORM inputs (Speech / Translation / NLLanguageRecognizer / AVSpeech on iOS): never in the vectors.
 * Intl.Segmenter output (zh/ja/th key words) differs from the OS tokenizers, so the key-word vectors cover space-separated scripts only. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const rd = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
export const PHRASES_PATH = 'native/shared/gen/content-pack/interpret-phrases.json';
export const VECTORS_PATH = 'native/shared/gen/vectors/interpret.json';

function sandbox() {
  const store = new Map();
  const sb = { console, Math, JSON, Date, localStorage: { getItem: k => (store.has(k) ? store.get(k) : null), setItem: (k, v) => store.set(k, String(v)), removeItem: k => store.delete(k) } };
  sb.self = sb; sb.globalThis = sb; vm.createContext(sb);
  return sb;
}
const run = (sb, f) => vm.runInContext(rd(f), sb, { filename: f });
const J = x => JSON.stringify(x, null, 2) + '\n';

export function interpretPhrases() {
  const sb = sandbox(); run(sb, 'web/cpack/interpret/phrases.js');
  const D = sb.INTERPRET_PHRASES;
  return J({ _doc: 'GENERATED by scripts/native/gen-interpret.mjs from web/cpack/interpret/phrases.js – do not edit by hand.', order: D.order, items: D.items.map(([g, t]) => ({ g, t })) });
}

export function interpretVectors() {
  const C = () => { const sb = sandbox(); run(sb, 'web/cpack/interpret/core.js'); return { sb, C: sb.InterpretCore }; };
  const { C: core } = C();
  const out = { _doc: 'GENERATED by scripts/native/gen-interpret.mjs from web/cpack/interpret/core.js – do not edit by hand.', langs: core.LOC, rtl: core.CODES.filter(l => core.dirOf(l) === 'rtl'), maxConv: core.MAX_CONV, maxTurn: core.MAX_TURN };
  out.speaker = [
    ['sure-a', { lang: 'es', confidence: 0.9 }, 'a'], ['sure-b-mic-a', { lang: 'en', confidence: 0.95 }, 'a'], ['unsure', { lang: 'es', confidence: 0.4 }, 'a'],
    ['other-lang', { lang: 'de', confidence: 0.99 }, 'b'], ['region-tag', { lang: 'es-MX', confidence: 0.8 }, 'a'], ['none', null, 'b'], ['edge-0.6', { lang: 'en', confidence: 0.6 }, 'a'],
  ].map(([id, det, side]) => ({ id, det, pair: { a: 'en', b: 'es' }, side, out: core.speaker(det, { a: 'en', b: 'es' }, side) }));
  const ks = [
    ['repeat-first', ['the market is open', 'open the market', 'a market'], 'en', 8, []],
    ['short-dropped', ['go to the big sea'], 'en', 8, []],
    ['known', ['the market is open', 'open the market'], 'en', 8, ['market']],
    ['limit-2', ['alpha beta gamma delta alpha beta'], 'en', 2, []],
    ['accents', ['¿Dónde está la estación? La estación de tren.'], 'es', 8, []],
    ['arabic', ['أين المحطة القريبة؟ المحطة'], 'ar', 8, []],
  ];
  out.keyWords = ks.map(([id, texts, lang, n, known]) => ({ id, texts, lang, n, known, out: core.keyWords(texts, lang, n, new Set(known)) }));
  const conv = { a: 'en', b: 'es', turns: [
    { from: 'a', src: 'Where is the station?', dst: 'es', tx: '¿Dónde está la estación?', ts: 1 },
    { from: 'b', src: 'Está cerca.', dst: 'en', tx: 'It is close.', ts: 2 },
    { from: 'a', src: 'Where is the station?', dst: 'es', tx: '¿Dónde está la estación?', ts: 3 },
    { from: 'a', src: 'Thanks', dst: 'es', tx: '', ts: 4 } ] };
  out.cards = ['en', 'es', 'vi', 'es-MX'].map(me => ({ id: 'me-' + me, conv, me, out: core.cards(conv, me) }));
  // history: add turns through the real code on a fresh storage
  const hist = (id, why, f) => { const { sb, C: c } = C(); f(c); return { id, why, out: sb.InterpretCore.load().convs.map(x => ({ id: x.id, a: x.a, b: x.b, t: x.t, n: x.turns.length, first: x.turns[0].src, last: x.turns[x.turns.length - 1].src })) }; };
  const pair = { a: 'en-US', b: 'es-ES' };
  out.history = [
    hist('new-conv-base-codes', 'language tags are cut to the base code; t = ts of the first turn', c => c.addTurn('c1', pair, { from: 'a', src: 'hi', dst: 'es', tx: 'hola', ts: 100 })),
    hist('append-same-conv', 'a second turn goes into the same conversation', c => { c.addTurn('c1', pair, { from: 'a', src: 'hi', dst: 'es', tx: 'hola', ts: 100 }); c.addTurn('c1', pair, { from: 'b', src: 'hola', dst: 'en', tx: 'hi', ts: 101 }); }),
    hist('newest-first', 'a new conversation is put in front', c => { c.addTurn('c1', pair, { from: 'a', src: 'one', dst: 'es', tx: 'uno', ts: 1 }); c.addTurn('c2', pair, { from: 'a', src: 'two', dst: 'es', tx: 'dos', ts: 2 }); }),
    hist('cap-turns', 'more than 200 turns: the oldest are dropped', c => { for (let i = 0; i < 205; i++) c.addTurn('c1', pair, { from: 'a', src: 's' + i, dst: 'es', tx: 't' + i, ts: i + 1 }); }),
    hist('cap-convs', 'more than 30 conversations: the oldest are dropped', c => { for (let i = 0; i < 33; i++) c.addTurn('c' + i, pair, { from: 'a', src: 's' + i, dst: 'es', tx: 't' + i, ts: i + 1 }); }),
  ];
  return J(out);
}
