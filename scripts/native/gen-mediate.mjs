/* Native P13 – Mediation (#/mediate). Reference = the REAL web/js/mediate-core.js (run in node:vm) over content/mediation/*.json.
 * Outputs: content-pack/mediation.json (all lessons, web list order = level then id; bundled in both apps) and vectors/mediate.json
 * (words / hit / copied / check / voices cases the native ports must reproduce). docs/specs/mediation.md. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = p => path.join(ROOT, p);
export const MEDIATION_PATH = 'native/shared/gen/content-pack/mediation.json';
const LEVELS = ['A2', 'B1', 'B2', 'C1', 'C2'];

function core() {
  const sb = { console }; sb.self = sb; sb.globalThis = sb; vm.createContext(sb);
  vm.runInContext(fs.readFileSync(R('web/js/mediate-core.js'), 'utf8'), sb, { filename: 'web/js/mediate-core.js' });
  return sb.MediateCore;
}
function lessons() {
  const dir = R('content/mediation');
  return fs.readdirSync(dir).filter(f => /^m\d+\.json$/.test(f)).sort().map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')))
    .sort((a, b) => LEVELS.indexOf(a.level) - LEVELS.indexOf(b.level) || a.id.localeCompare(b.id));
}

export function mediationPack() {
  const items = lessons().map(x => ({ id: x.id, level: x.level, lo: x.lo, activity: x.activity, title: x.title, scenario: x.scenario, source: x.source, task: x.task,
    points: x.points, leave_out: x.leave_out || [], model: x.model, useful: x.useful || [], tips: x.tips || [], explain: x.explain || '' }));
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-mediate.mjs from content/mediation/*.json (order = level then id, as web/cpack/mediation/index.js). source.kind: announcement|text|email|notice|talk (text = string|string[]) · dialogue (lines[{s,t}]) · chart (caption, cols, rows[[label,…]], unit, note). task.mode write|speak. points/leave_out checks = groups of phrases: a point is met when EVERY group has at least one phrase in the text (case-insensitive). Listen-first (text hidden until heard or Show text) for B2/C1/C2 except charts.',
    levels: LEVELS, listenFirst: ['B2', 'C1', 'C2'], copyRun: 8, items }) + '\n';
}

export function mediationVectors() {
  const MC = core(), L = lessons();
  const wordsIn = ['', 'Platform 9, not platform 4.', "It's 14:50 – about 15% late!", 'e-mail me at 5.30pm.', 'don’t   panic', '   ', '3.5 million', 'A-B test'];
  const hitCases = [
    { text: 'Go to PLATFORM nine now', checks: [['platform 9', 'platform nine']] }, { text: 'platform 4', checks: [['platform 9', 'platform nine']] },
    { text: 'Leaves at 14:50 from platform 9', checks: [['14:50'], ['platform 9']] }, { text: 'Leaves at 14:50', checks: [['14:50'], ['platform 9']] },
    { text: 'It’s fine', checks: [["it's"]] }, { text: 'anything', checks: [] }, { text: 'ten–to three', checks: [['ten-to three']] },
  ];
  const copyCases = [];
  for (const x of L.slice(0, 6)) {
    const src = MC.sourceText(x.source), w = MC.words(src);
    copyCases.push({ id: x.id, text: w.slice(0, 9).join(' '), n: 8, out: MC.copied(w.slice(0, 9).join(' '), src, 8) });
    copyCases.push({ id: x.id, text: w.slice(0, 7).join(' '), n: 8, out: MC.copied(w.slice(0, 7).join(' '), src, 8) });
    copyCases.push({ id: x.id, text: x.model, n: 8, out: MC.copied(x.model, src, 8) });
  }
  const sourceText = L.map(x => ({ id: x.id, out: MC.sourceText(x.source) }));
  const check = [];
  for (const x of L) {
    const half = x.model.split(/(?<=[.!?])\s+/).slice(0, 1).join(' ');
    const withExtra = x.model + ' ' + ((x.leave_out || [])[0]?.checks?.[0]?.[0] || '');
    const copy = MC.words(MC.sourceText(x.source)).slice(0, 10).join(' ');
    for (const [kind, text] of [['model', x.model], ['empty', ''], ['half', half], ['extra', withExtra], ['copy', copy], ['model-lower', x.model.toLowerCase()]]) check.push({ id: x.id, kind, text, out: MC.check(x, text) });
  }
  const voices = L.filter(x => x.source.kind === 'dialogue').map(x => ({ id: x.id, out: MC.voices(x.source) }));
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-mediate.mjs from web/js/mediate-core.js (MediateCore.words/hit/copied/sourceText/check/voices) over content/mediation. check.out = {n, inRange, points[{id,idea,ok}], extra[idea], copied}. words: tokens [A-Za-z0-9][A-Za-z0-9\'’:%.-]* with trailing dots stripped.',
    words: wordsIn.map(s => ({ in: s, out: MC.words(s) })), hit: hitCases.map(c => ({ ...c, out: MC.hit(c.text, c.checks) })), copied: copyCases, sourceText, check, voices }) + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) console.log(mediationPack().length, mediationVectors().length);
