/* Native P10 (part) – Adaptive entry test (#/placement). Reference = the REAL web/js/placement.js (Placement.posterior / estimate / bandOf / cefrOf / stageOf / nextLevel / take) run in node:vm,
 * plus the `settings.placement` literal that route's finish() writes (read out of the source, evaluated here). Question banks come from the same web data the route uses (IELTS_DATA.TOPICS words, GRAMMAR quiz).
 * Outputs: content-pack/placement-bank.json (compact bank, bundled in both apps: 4 levels x 90 vocabulary + 50 grammar items) and vectors/placement.json
 * (posterior / estimate / band / cefr / stage / nextLevel / take / record cases + full 20-question scenarios over the bank). Spec: docs/specs/upgrade-2026-11.md #7. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { grammarSource } from './gen-learn.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = p => path.join(ROOT, p);
export const PLACEMENT_PATH = 'native/shared/gen/content-pack/placement-bank.json';
const LADDER = ['A2', 'B1', 'B2', 'C1'];
const VI = /[ăđơưạảấầẩẫậắằẳẵặẹẻẽếềểễệỉịọỏốồổỗộớờởỡợụủứừửữựỳỵỷỹ]/i; // same filter as the web gpool
const PER_VOCAB = 90, PER_GRAMMAR = 50;
const fnv = s => { let h = 0x811c9dc5; for (const ch of String(s)) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; } return h; };

function webPlacement() {
  const src = fs.readFileSync(R('web/js/placement.js'), 'utf8');
  const sb = { console, Math, JSON, Date, t: s => s }; sb.window = sb; sb.globalThis = sb; sb.self = sb; vm.createContext(sb);
  vm.runInContext(src, sb, { filename: 'web/js/placement.js' }); // no App → stops after exporting g.Placement
  const m = /state\.settings\.placement = (\{[^;]*\});/.exec(src);
  if (!m) throw new Error('placement: settings.placement literal not found in web/js/placement.js – update scripts/native/gen-placement.mjs');
  const B = JSON.parse(JSON.stringify(vm.runInNewContext('(' + /const B = (\{[^}]*\});/.exec(src)[1] + ')')));
  const consts = (() => { const c = /const A = ([\d.]+), MU = ([\d.]+), SD = ([\d.]+), N = (\d+);/.exec(src); return { A: +c[1], MU: +c[2], SD: +c[3], N: +c[4] }; })();
  const record = (E, n, now) => vm.runInNewContext('(' + m[1].replace(/\bDate\.now\(\)/, String(now)) + ')', { E, Math });
  return { P: sb.Placement, record, B, consts };
}

function webWords() {
  const sb = { console, Math, JSON, t: s => s }; sb.self = sb; sb.globalThis = sb; sb.window = sb; vm.createContext(sb);
  for (const f of ['data.js', 'lib/topics-more.js', '../cpack/lib/skills.js', '../cpack/lib/awl.js', 'lib/ngsl.js', 'lib/ngsl2.js', 'lib/office.js', '../cpack/lib/tsl-a.js', '../cpack/lib/tsl-b.js', '../cpack/lib/domain-a.js', '../cpack/lib/domain-b.js', '../cpack/lib/exam-vocab.js', '../cpack/lib/exam-vocab2.js', '../cpack/lib/exam-vocab3.js', '../cpack/lib/nawl.js', '../cpack/lib/bsl.js'])
    vm.runInContext(fs.readFileSync(R('web/js/' + f), 'utf8'), sb, { filename: 'web/js/' + f });
  vm.runInContext(fs.readFileSync(R('web/js/distract.js'), 'utf8'), sb, { filename: 'web/js/distract.js' });
  return { topics: sb.IELTS_DATA.TOPICS, D: sb.Distract };
}

export function placementPack() {
  const { B } = webPlacement(), { topics, D } = webWords(), G = grammarSource().G;
  // vocabulary pool = web prep(): unique single words, known level, with a meaning, not a phrase; A1 -> A2 and C2 -> C1 (the test ladder)
  const seen = new Set(), vocab = [];
  for (const w of topics.flatMap(tp => tp.words)) {
    const k = String(w.word || '').toLowerCase();
    if (!k || seen.has(k) || /\s/.test(k) || B[w.level] == null || !(w.vi || w.def) || D.posOf(w.pos) === 'phr') continue;
    seen.add(k);
    const lv = w.level === 'A1' ? 'A2' : w.level === 'C2' ? 'C1' : w.level;
    if (!LADDER.includes(lv) || !w.vi || !w.def || w.vi.length > 70 || w.def.length > 120 || !/^[A-Za-z][A-Za-z'-]*$/.test(w.word)) continue; // compact bank: clean single words with both meanings
    vocab.push({ id: 'v:' + w.word, lv, w: w.word, pos: D.posOf(w.pos), vi: w.vi, def: w.def });
  }
  const grammar = [];
  for (const l of G) (l.quiz || []).forEach((q, k) => {
    if (!LADDER.includes(l.level) || !q || !Array.isArray(q.options) || q.options.length < 3 || VI.test(q.q) || q.options.some(o => VI.test(o)) || !Number.isInteger(q.answer)) return;
    grammar.push({ id: 'g:' + l.id + ':' + k, lv: l.level, q: q.q, options: q.options, answer: q.answer });
  });
  const pick = (xs, per) => LADDER.flatMap(lv => xs.filter(x => x.lv === lv).sort((a, b) => fnv(a.id) - fnv(b.id) || (a.id < b.id ? -1 : 1)).slice(0, per));
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-placement.mjs from the web data the #/placement route uses (IELTS_DATA words, GRAMMAR quiz) – compact bank, deterministic by FNV(id). vocab: lv = test ladder level (A1->A2, C2->C1), pos = normalised part of speech (n v adj adv …), vi / def = meaning shown by UI language. grammar: q (with ___), options, answer index.',
    v: 1, n: webPlacement().consts.N, ladder: LADDER, vocab: pick(vocab, PER_VOCAB), grammar: pick(grammar, PER_GRAMMAR) }) + '\n';
}

export function placementVectors(packText) {
  const { P, record, B, consts } = webPlacement(), pack = JSON.parse(packText);
  const r = (kind, lv, ans, c) => (c === undefined ? { kind, lv, r: ans } : { kind, lv, r: ans, c });
  const seq = (n, f) => Array.from({ length: n }, (_, i) => f(i));
  const sets = {
    empty: [],
    one_right_b1: [r('vocab', 'B1', 'right', 0.25)],
    one_wrong_b1: [r('vocab', 'B1', 'wrong', 0.25)],
    one_idk_b2: [r('grammar', 'B2', 'idk', 0.25)],
    all_right_a2: seq(10, i => r(i % 2 ? 'grammar' : 'vocab', 'A2', 'right', 0.25)),
    all_wrong_a2: seq(10, i => r(i % 2 ? 'grammar' : 'vocab', 'A2', 'wrong', 0.25)),
    all_right_c1: seq(20, i => r(i % 2 ? 'grammar' : 'vocab', 'C1', 'right', 0.25)),
    all_wrong_c1: seq(20, i => r(i % 2 ? 'grammar' : 'vocab', 'C1', 'wrong', 0.25)),
    all_idk: seq(20, i => r(i % 2 ? 'grammar' : 'vocab', LADDER[i % 4], 'idk', 0.25)),
    mixed_20: seq(20, i => r(i % 2 ? 'grammar' : 'vocab', LADDER[(i * 3) % 4], ['right', 'wrong', 'idk', 'right', 'right'][i % 5], i % 2 ? 1 / 3 : 0.25)),
    default_c: [{ kind: 'vocab', lv: 'B2', r: 'right' }, { kind: 'vocab', lv: 'B2', r: 'wrong' }, { kind: 'grammar', lv: 'B1', r: 'right', c: null }],
    unknown_level: [r('vocab', 'ZZ', 'right', 0.25), r('vocab', 'ZZ', 'wrong', 0.25)],
    cefr_a1_c2: [r('vocab', 'A1', 'right', 0.25), r('vocab', 'C2', 'wrong', 0.25), r('grammar', 'C2', 'right', 0.2)],
    vocab_only: seq(10, i => r('vocab', LADDER[i % 4], i < 5 ? 'right' : 'wrong', 0.25)),
    grammar_only: seq(10, i => r('grammar', LADDER[i % 4], i < 7 ? 'right' : 'wrong', 0.25)),
    weak_grammar: [...seq(6, i => r('vocab', LADDER[i % 4], 'right', 0.25)), ...seq(6, i => r('grammar', LADDER[i % 4], 'wrong', 0.25))],
    tie_vocab_grammar: [r('vocab', 'B1', 'right', 0.25), r('grammar', 'B1', 'right', 0.25)],
    ladder_up: [r('vocab', 'B1', 'right', 0.25), r('vocab', 'B2', 'right', 0.25), r('vocab', 'C1', 'right', 0.25), r('vocab', 'C1', 'wrong', 0.25)],
  };
  const respCases = Object.entries(sets).map(([name, resp]) => ({ name, resp }));
  const posterior = respCases.map(c => ({ ...c, out: P.posterior(c.resp) }));
  const estimate = respCases.map(c => ({ ...c, out: P.estimate(c.resp) }));
  const nextLevel = respCases.map(c => ({ ...c, out: P.nextLevel(c.resp) }));
  const ths = [-2, -1, -0.2, 0, 0.3, 0.5, 0.75, 1, 1.2, 1.5, 2, 2.5, 3, 3.5, 4, 5, 0.1666, 0.8333];
  const bandOf = ths.map(th => ({ in: th, out: P.bandOf(th) }));
  const bands = [3, 3.5, 3.9, 4, 4.5, 5, 5.5, 6, 6.5, 6.9, 7, 7.5, 8, 8.5];
  const cefrOf = bands.map(b => ({ in: b, out: P.cefrOf(b) }));
  const stageOf = [3, 4.5, 5, 5.5, 6, 6.5, 7, 8.5].map(b => ({ in: b, out: P.stageOf(b) }));
  // take(): level preference then the nearest level (below first, then above), unused only, random index inside the level
  const mk = (lv, n) => seq(n, i => ({ id: `${lv}-${i}`, lv }));
  const full = LADDER.flatMap(lv => mk(lv, 3)), onlyB2 = mk('B2', 2), spread = [...mk('A2', 1), ...mk('C1', 1)];
  const takeCases = [];
  const addTake = (name, pool, lv, used, rnd) => { const u = new Set(used), it = []; const rs = [...rnd]; let k = 0; const out = P.take(pool, lv, u, () => rs[k++ % rs.length]); takeCases.push({ name, pool, lv, used, rnd, out: out ? out.id : null, usedAfter: [...u] }); return it; };
  addTake('exact_first', full, 'B1', [], [0]); addTake('exact_last', full, 'B1', [], [0.999]); addTake('exact_mid', full, 'B2', [], [0.5]);
  addTake('skip_used', full, 'B1', ['B1-0', 'B1-1'], [0]); addTake('level_exhausted_goes_below', full, 'B1', ['B1-0', 'B1-1', 'B1-2'], [0]);
  addTake('a2_exhausted_goes_up', full, 'A2', ['A2-0', 'A2-1', 'A2-2'], [0]); addTake('c1_exhausted_goes_below', full, 'C1', ['C1-0', 'C1-1', 'C1-2'], [0.9]);
  addTake('below_before_above', spread, 'B2', [], [0]); addTake('only_far_level', onlyB2, 'A2', [], [0]); addTake('all_used', onlyB2, 'B2', ['B2-0', 'B2-1'], [0]);
  addTake('empty_pool', [], 'B1', [], [0]); addTake('unknown_level', full, 'Z9', [], [0]);
  // what finish() saves
  const NOW = 1767603600000;
  const recs = ['mixed_20', 'all_right_c1', 'all_idk', 'weak_grammar', 'one_wrong_b1'].map(name => { const resp = sets[name], E = P.estimate(resp); return { name, resp, now: NOW, out: record(E, resp.length, NOW) }; });
  // 20-question scenarios over the bank: kind alternation, nextLevel per kind, take(), c = 1 / options, answers by policy
  const lcg = seed => { let x = seed >>> 0; return () => { x = (Math.imul(x, 1664525) + 1013904223) >>> 0; return x / 4294967296; }; };
  const pol = { right: () => 'right', wrong: () => 'wrong', idk: () => 'idk', alt: i => (i % 2 ? 'wrong' : 'right'), ladder: (i, lv) => (lv === 'A2' || lv === 'B1' ? 'right' : 'wrong'), mix: (i, lv) => (i % 3 === 0 ? 'idk' : lv === 'A2' || lv === 'B1' ? 'right' : 'wrong') };
  const scenarios = [];
  for (const [seed, policy] of [[1, 'right'], [2, 'wrong'], [3, 'idk'], [4, 'alt'], [5, 'ladder'], [42, 'mix'], [7, 'ladder'], [99, 'right']]) {
    const rnd = lcg(seed), used = new Set(), resp = [], steps = [];
    const vp = pack.vocab.map(x => ({ id: x.id, kind: 'vocab', lv: x.lv })), gp = pack.grammar.map(x => ({ id: x.id, kind: 'grammar', lv: x.lv, n: x.options.length }));
    for (let i = 0; i < consts.N; i++) {
      const kind = !gp.length ? 'vocab' : !vp.length ? 'grammar' : resp.length % 2 ? 'grammar' : 'vocab';
      const want = P.nextLevel(resp.filter(x => x.kind === kind));
      const it = P.take(kind === 'vocab' ? vp : gp, want, used, rnd); if (!it) break;
      const c = kind === 'vocab' ? 0.25 : 1 / it.n, ans = pol[policy](i, it.lv);
      resp.push({ kind, lv: it.lv, r: ans, c }); steps.push({ kind, want, id: it.id, lv: it.lv, r: ans, c });
    }
    scenarios.push({ seed, policy, steps, estimate: P.estimate(resp), record: record(P.estimate(resp), resp.length, NOW), now: NOW });
  }
  return JSON.stringify({ _doc: 'GENERATED by scripts/native/gen-placement.mjs from web/js/placement.js (Placement.posterior/estimate/bandOf/cefrOf/stageOf/nextLevel/take run in node:vm; record = the settings.placement literal of the route). resp item {kind: vocab|grammar, lv, r: right|wrong|idk, c: chance of a lucky guess | absent = 0.25}. take: rnd = the values returned by successive rnd() calls. scenarios: the ask() loop over content-pack/placement-bank.json with rnd = LCG (x = x*1664525+1013904223 mod 2^32, value = x/2^32, seed first): kind = vocab for even index, grammar for odd; want = nextLevel(answers of that kind); c = 0.25 for vocabulary, 1/options for grammar; policy decides the answer (right|wrong|idk|alt = right on even index|ladder = right at A2/B1|mix = idk every 3rd, else ladder).',
    consts: { ...consts, ladder: LADDER, B }, posterior, estimate, nextLevel, bandOf, cefrOf, stageOf, take: takeCases, record: recs, scenarios }) + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) { const p = placementPack(); console.log(p.length, placementVectors(p).length); }
