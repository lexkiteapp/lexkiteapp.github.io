#!/usr/bin/env node
/* Native starter content pack (docs/specs/native-apps.md §3): the few KB a fresh native install needs to show Today and run the
 * FIRST lesson offline before anything is downloaded. Built from the SAME web data (no copies by hand):
 *   web/js/data.js + web/js/lib/ngsl.js (IELTS_DATA topics, real word entries) · web/js/path.js (STAGES order, CORE units, PART size,
 *   lesson STEPS) · web/js/core.js (DEFAULT_SETTINGS goal/new-words). Everything else (later lessons, lexicon shards, audio, images)
 *   is fetched from the CDN/API exactly like web and cached.
 * Usage: node scripts/native/content-pack.mjs [--check]   (scripts/native/gen.mjs also writes/checks it). */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const R = p => path.join(ROOT, p);
export const PACK_DIR = 'native/shared/gen/content-pack';
export const PACK_MAX_BYTES = 32 * 1024; // keep the bundled pack tiny (documented in the spec)

export function contentPack() {
  const sb = { console, Math, JSON, t: s => s }; sb.self = sb; sb.globalThis = sb; vm.createContext(sb);
  for (const f of ['web/js/data.js', 'web/js/lib/ngsl.js']) vm.runInContext(fs.readFileSync(R(f), 'utf8'), sb, { filename: f });
  const core = { console, Date, Math, navigator: {}, setTimeout, clearTimeout }; core.self = core; vm.createContext(core);
  vm.runInContext(fs.readFileSync(R('web/js/core.js'), 'utf8'), core, { filename: 'web/js/core.js' });
  const pathJs = fs.readFileSync(R('web/js/path.js'), 'utf8');
  const cm = pathJs.match(/const CORE = (\[[^\]]+\]), PART = (\d+)/), stm = [...pathJs.matchAll(/\['(learn|match|listen|test)', '([^']+)'/g)];
  if (!cm || stm.length !== 4) throw new Error('content-pack: CORE/PART/STEPS not found in web/js/path.js');
  const CORE = JSON.parse(cm[1].replace(/'/g, '"')), PART = +cm[2];
  const topic = sb.IELTS_DATA.TOPICS.find(t => t.id === CORE[0]);
  if (!topic) throw new Error(`content-pack: first unit "${CORE[0]}" not in IELTS_DATA`);
  // first sub-lesson "ngsl1.1": same slicing as App.subTopic (parts = ceil(n / PART), lesson k = words[round(k·n/parts) … round((k+1)·n/parts))
  const n = topic.words.length, parts = Math.ceil(n / PART), words = topic.words.slice(0, Math.round(n / parts));
  const { dailyGoal, dailyNew } = core.Core.DEFAULT_SETTINGS;
  const lesson = {
    id: `${CORE[0]}.1`, unit: CORE[0], stage: 's0', emoji: topic.emoji, nameId: 'lesson.coreRange', nameKey: 'Từ cốt lõi {a}–{b}', nameVars: { a: 1, b: words.length },
    steps: stm.map(m => m[1]),
    words: words.map(w => ({ word: w.word, ipa: w.ipa, ipaUS: w.ipaUS || undefined, pos: w.pos, vi: w.vi, def: w.def, ex: w.ex, col: w.col.length ? w.col : undefined, syn: w.syn.length ? w.syn : undefined, level: w.level, emoji: w.emoji })),
  };
  const today = { v: 1, firstLesson: lesson.id, nextLesson: `${CORE[0]}.2`, dailyGoal, dailyNew }; // nextLesson is fetched like web (not bundled)
  const head = { _doc: 'GENERATED by scripts/native/content-pack.mjs from web/js/data.js, web/js/lib/ngsl.js, web/js/path.js, web/js/core.js – do not edit by hand.' };
  const files = new Map([
    [`${PACK_DIR}/today.json`, JSON.stringify({ ...head, ...today }, null, 2) + '\n'],
    [`${PACK_DIR}/lesson-${lesson.id}.json`, JSON.stringify({ ...head, ...lesson }, null, 2) + '\n'],
  ]);
  const bytes = [...files.values()].reduce((s, x) => s + Buffer.byteLength(x), 0);
  if (bytes > PACK_MAX_BYTES) throw new Error(`content-pack: ${bytes} B > ${PACK_MAX_BYTES} B budget – keep the starter pack small`);
  return { files, bytes, words: words.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { files, bytes, words } = contentPack(), check = process.argv.includes('--check');
  let drift = 0;
  for (const [rel, s] of files) {
    const cur = fs.existsSync(R(rel)) ? fs.readFileSync(R(rel), 'utf8') : null;
    if (cur === s) continue;
    if (check) { drift++; console.error('DRIFT ' + rel); } else { fs.mkdirSync(path.dirname(R(rel)), { recursive: true }); fs.writeFileSync(R(rel), s); console.log('wrote', rel); }
  }
  if (drift) process.exit(1);
  console.log(`content-pack ${check ? 'check' : 'write'} OK: ${files.size} files, ${words} words, ${bytes} B`);
}
