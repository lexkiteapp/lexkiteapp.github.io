"""Spell->Sound rule miner (docs/specs/spell-sound.md): content/video/teach2d/rules.json + the audited word bank -> rules-words.json.
Per rule: every bank word whose spelling matches AND whose US IPA proves the rule (ipa_re / ipa_absent), ordered by CEFR then NGSL then spelling, top 6.
A word whose IPA does not show the rule is dropped - never hand-edit an IPA. Deterministic, no AI. Called by `gen.py --rules [--check]`."""
import json, os, re
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
RULES_F, OUT_F = f'{ROOT}/content/video/teach2d/rules.json', f'{ROOT}/content/video/teach2d/rules-words.json'
TOP, MIN_WORDS, CEFR_RANK = 6, 2, {'A1': 0, 'A2': 1, 'B1': 2, 'B2': 3}   # C1+ words are not "common" - never taught
INFL = ('s', 'es', 'ed', 'd', 'ing', 'er', 'r', 'or', 'ly', 'ful', 'y', 'ist', 'ical')   # derived forms of a word already in the rule


def plain(ipa): return re.sub('[/ˈˌ]', '', ipa or '')   # stress marks + slashes off: the rule tests the segments


def silent_span(m):   # (start, end) of the silent letters: the one named group s / s2 / s3 that matched
    for g in ('s', 's2', 's3'):
        if g in m.re.groupindex and m.start(g) >= 0: return [m.start(g), m.end(g)]
    return None


def check(rule, w, ipa):   # -> silent span if the word shows the rule, else None
    m = re.search(rule['pattern'], w)
    if not m or not (sp := silent_span(m)): return None
    p = plain(ipa)
    if 'ipa_re' in rule and not re.search(rule['ipa_re'], p): return None
    if 'ipa_absent' in rule and re.search(rule['ipa_absent'], p): return None
    return sp


def derived(w, c):   # w = a word of c + an inflection / derivation suffix
    for s in INFL:
        b = w[:-len(s)]
        if w.endswith(s) and len(b) >= 3 and (b in c or (b + 'y' in c and b + 'y' != w)): return True
    return False


def mine(F, ngsl):   # F = gen.facts()['words'], ngsl = set of NGSL words -> {rule id: [rows]}
    out = {}
    for r in json.load(open(RULES_F))['rules']:
        c = {}
        for w, A in F.items():
            if not re.fullmatch('[a-z]+', w) or not A['ipa'] or A['cefr'] not in CEFR_RANK: continue
            if (sp := check(r, w, A['ipa'])) is not None: c[w] = dict(word=w, ipa=A['ipa'], cefr=A['cefr'], silent=sp, letter=w[sp[0]:sp[1]], **{'def': A['def'], 'ex': A['ex'], 'em': A['em']})
        allw = dict(c)
        for w in list(c):   # one lesson word per family: knocks / knocked / writer / hourly go, knock / write / hour stay (psychology + -ist / -ical: the -y drops)
            if derived(w, c): del c[w]
        if len(c) < MIN_WORDS: c = allw   # a rare rule (ps-, -bt): its derived forms are all there is, keep them
        rows = sorted(c.values(), key=lambda x: (CEFR_RANK[x['cefr']], x['word'] not in ngsl, x['word']))[:TOP]
        out[r['id']] = rows if len(rows) >= MIN_WORDS else []
    return out


def build(F, ngsl):
    R = {r['id']: r for r in json.load(open(RULES_F))['rules']}; M = mine(F, ngsl)
    return dict(_note='GENERATED by gen.py --rules from rules.json + the audited word bank (docs/specs/spell-sound.md). Do not edit by hand.',
                rules=[dict(id=i, title=R[i]['title'], kind=R[i]['kind'], target=R[i]['target'], words=ws) for i, ws in M.items() if ws])


def dump(d): return json.dumps(d, indent=1, ensure_ascii=False) + '\n'
