#!/usr/bin/env python3
"""Teach2D bank (docs/VIDEO-TEACH2D.md "Batch"): only an episode whose short AND wide renders passed every qc.py gate with score >= 90
(and whose video is not a byte copy of another) enters content/video/teach2d/bank.json. Videos stay CI artifacts (tv-bank-<run>, 90 days).
  python3 bank.py collect <artifacts_dir> <ep_list_json> <run_id> <delta.json> <scoreboard.md> [<bank_dir>]   -> exit 0 (verdicts are data)
  python3 bank.py merge <delta.json>      -> bank.json + BANK.md (idempotent per fresh main: commit-regen.sh re-runs it after a rebase)
A red render counts one try; gen.py --todo stops offering an episode after 2 red tries (left for a person, listed in BANK.md)."""
import glob, hashlib, json, os, shutil, sys, time
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
BANK_F, MD_F, PUB_F, MIN = f'{ROOT}/content/video/teach2d/bank.json', f'{ROOT}/content/video/teach2d/BANK.md', f'{ROOT}/content/video/teach2d/PUBLISH.md', 90


def load():
    return json.load(open(BANK_F)) if os.path.exists(BANK_F) else dict(_note='Teach2D episodes that passed QC (bank.py). Videos: CI artifact tv-bank-<run> (90 days). Do not edit by hand.', eps={})


def sha(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''): h.update(b)
    return h.hexdigest()[:16]


def collect(art, eps, run, out, md, bank_dir=None):
    known = {s for e in load()['eps'].values() for s in (e.get('sha') or {}).values()}; seen = set(); D = {}
    for ep in eps:
        r = dict(run=str(run), at=time.strftime('%Y-%m-%dT%H:%MZ', time.gmtime()), score={}, sha={}, why=[])
        for fm in ('short', 'wide'):
            q = next((json.load(open(f)) for f in glob.glob(f'{art}/tv-{ep}-{fm}-*/qc.json')), None)
            if not q: r['why'].append(f'{fm}: no render'); continue
            r['score'][fm] = q['score']; bad = [k for k, g in q['gates'].items() if not g['ok']]
            if bad or not q['ok'] or q['score'] < MIN: r['why'].append(f"{fm}: score {q['score']}" + (f" gates {','.join(bad)}" if bad else ''))
            mp4 = next(iter(glob.glob(f'{art}/tv-{ep}-{fm}-*/{ep}-{fm}.mp4')), None)
            if not mp4: r['why'].append(f'{fm}: mp4 missing'); continue
            h = sha(mp4); r['sha'][fm] = h
            if h in known or h in seen: r['why'].append(f'{fm}: duplicate video')
            seen.add(h)
        r['state'] = 'failed' if r['why'] else 'banked'; D[ep] = r
        if r['state'] == 'banked' and bank_dir:
            os.makedirs(bank_dir, exist_ok=True)
            for fm, pat in (('short', f'{art}/tv-{ep}-short-*/phone/{ep}.mp4'), ('wide', f'{art}/tv-{ep}-wide-*/{ep}-wide.mp4'), ('poster', f'{art}/tv-{ep}-short-*/{ep}-short.poster.jpg')):
                for p in glob.glob(pat)[:1]: shutil.copy(p, f"{bank_dir}/{ep}-{fm}{os.path.splitext(p)[1]}")
    json.dump(D, open(out, 'w'), indent=1)
    ok = [e for e, r in D.items() if r['state'] == 'banked']
    L = [f'# Teach2D batch – run {run}', '', f'**{len(ok)} / {len(D)} banked** (both formats, every gate green, score >= {MIN})', '',
         '| episode | short | wide | verdict |', '|---|---|---|---|']
    L += [f"| {e} | {r['score'].get('short', '–')} | {r['score'].get('wide', '–')} | {'✅ banked' if r['state'] == 'banked' else '❌ ' + '; '.join(r['why'])} |" for e, r in D.items()]
    open(md, 'w').write('\n'.join(L) + '\n'); print('\n'.join(L[:3]))


def merge(delta):
    B = load(); D = json.load(open(delta))
    for ep, r in D.items():
        old = B['eps'].get(ep, {})
        if old.get('state') == 'banked': continue   # never downgrade a banked episode
        r = dict(r, tries=old.get('tries', 0) + (r['state'] == 'failed')); B['eps'][ep] = r
    B['eps'] = dict(sorted(B['eps'].items()))
    json.dump(B, open(BANK_F, 'w'), indent=1, ensure_ascii=False); open(BANK_F, 'a').write('\n')
    E = B['eps']; ok = {e: r for e, r in E.items() if r['state'] == 'banked'}; tpl = {}
    for e in ok: t = e.split('_')[1]; tpl[t] = tpl.get(t, 0) + 1
    L = ['# Teach2D bank – score table', '', '> Generated by `scripts/video/teach2d/bank.py merge` (teach-video.yml). Banked = short 9:16 + wide 16:9 both QC >= 90 with every gate green.', '',
         f"**{len(ok)} banked** ({', '.join(f'{t} {n}' for t, n in sorted(tpl.items()))}) · {sum(r['state'] == 'failed' for r in E.values())} red (2 red tries = left for a person)", '',
         '| episode | short | wide | state | run |', '|---|---|---|---|---|']
    L += [f"| {e} | {r['score'].get('short', '–')} | {r['score'].get('wide', '–')} | {'banked' if r['state'] == 'banked' else 'red ×' + str(r.get('tries', 1)) + ': ' + '; '.join(r['why'])} | {r['run']} |" for e, r in E.items()]
    open(MD_F, 'w').write('\n'.join(L) + '\n'); print(L[4])
    B_ = {e: r for e, r in E.items() if r.get('publish_block')}
    open(PUB_F, 'w').write('\n'.join(['# Teach2D – blocked from auto-publishing', '', '> Generated by `scripts/video/teach2d/bank.py merge` from `autopub_gate.py` reasons. A clip listed here is never published.', '', f'**{len(B_)} blocked**', '', '| episode | reasons |', '|---|---|'] + [f"| {e} | {', '.join(r['publish_block'])} |" for e, r in B_.items()]) + '\n')


if __name__ == '__main__':
    a = sys.argv
    if a[1] == 'collect': collect(a[2], json.loads(a[3]), a[4], a[5], a[6], a[7] if len(a) > 7 else None)
    elif a[1] == 'merge': merge(a[2])
    else: sys.exit(__doc__)
