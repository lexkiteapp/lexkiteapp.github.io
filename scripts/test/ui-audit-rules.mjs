// Test luật chấm của máy soát UI (scripts/test/lib/ui-audit-rules.mjs): mỗi luật bắt đúng, ô sạch không có lỗi, mức đúng.
import { audit, SEV_ORDER } from './lib/ui-audit-rules.mjs';
let fail = 0; const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fail++; };
const clean = { vw: 375, docW: 375, textLen: 500, errs: [], covered: [], contrast: [{ ratio: 7, big: false, text: 'a' }], primary: 1, primaryInFold: true, placeholders: [], emptyBoxes: [], brokenImgs: [], small: [] };
const rules = m => audit({ ...clean, ...m }).map(i => i.rule + ':' + i.sev);
ok(audit(clean).length === 0, 'ô sạch → không lỗi');
ok(rules({ docW: 420 }).includes('overflow:high'), 'tràn ngang >8px → cao');
ok(audit({ ...clean, docW: 380 }).length === 0, 'lệch ≤8px (thanh cuộn) không báo');
ok(rules({ textLen: 5 }).includes('empty:high'), 'màn trống → cao');
ok(rules({ errs: ['x is not defined'] }).includes('js:high'), 'lỗi JS → cao');
ok(rules({ covered: [{ text: 'Free', el: 'p', by: 'button.cta' }] }).includes('covered:high'), 'chữ bị che → cao');
ok(rules({ contrast: [{ ratio: 3.2, big: false, text: 'x' }] }).includes('contrast:medium'), 'tương phản 3.2 chữ thường → trung');
ok(!rules({ contrast: [{ ratio: 3.2, big: true, text: 'x' }] }).some(r => r.startsWith('contrast')), 'chữ lớn 3.2 đạt (ngưỡng 3)');
ok(rules({ primaryInFold: false }).includes('cta-fold:medium'), 'nút chính ngoài màn đầu → trung');
ok(!rules({ primary: 0, primaryInFold: null }).some(r => r.startsWith('cta-fold')), 'không có nút chính → không báo');
ok(rules({ placeholders: ['undefined'] }).includes('placeholder:medium'), 'undefined lọt giao diện → trung');
ok(rules({ emptyBoxes: ['div.bubble'] }).includes('empty-box:medium'), 'bong bóng trống → trung');
ok(rules({ small: [{ text: 'x', w: 30, h: 30 }] }).includes('tap:low'), '1–2 vùng chạm nhỏ → thấp');
ok(rules({ small: [1, 2, 3].map(() => ({ text: 'x', w: 30, h: 30 })) }).includes('tap:medium'), '≥3 vùng chạm nhỏ → trung');
ok(audit({ measureFail: 'boom' })[0].sev === 'high', 'đo hỏng → cao (không im lặng)');
ok(SEV_ORDER.join() === 'high,medium,low', 'thứ tự mức');
process.exit(fail ? 1 : 0);
