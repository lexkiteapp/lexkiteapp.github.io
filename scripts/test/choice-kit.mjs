// Test web/js/choice-kit.js bằng jsdom: phím A–D/1–4 chọn đúng câu, bỏ qua khi đang gõ, gạch đáp án (chuột phải) + nhớ qua lần vẽ lại, chia cột.
import fs from 'node:fs';
import jsdom from 'jsdom';
const { JSDOM } = jsdom;
let fails = 0, n = 0; const ok = (c, m) => { n++; if (!c) { fails++; console.log('✗', m); } };
const dom = new JSDOM(`<!doctype html><body><div id="root"></div><div class="body" id="b"><section id="a"></section><section id="q"></section></div></body>`, { url: 'https://lexkite.com/app/#/mock', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.matchMedia = () => ({ matches: false, addEventListener() {} });
w.HTMLElement.prototype.getBoundingClientRect = function () { return { top: 10, bottom: 40, left: 0, right: 1000, width: 1000, height: 30 }; };
w.eval(fs.readFileSync(new URL('../../web/js/choice-kit.js', import.meta.url), 'utf8'));
const $ = s => w.document.querySelector(s);
const q = (name, k) => `<div>${['x', 'y', 'z', 'w'].slice(0, k).map(v => `<label><input type="radio" name="${name}" value="${v}"> ${v}</label>`).join('')}</div>`;
const draw = () => { $('#root').innerHTML = q('q1', 4) + q('q2', 4) + '<input type="text" id="gap">'; };
draw();
const kit = w.ChoiceKit.attach($('#root'), { key: 't1' });
const key = (k, target = w.document.body) => target.dispatchEvent(new w.KeyboardEvent('keydown', { key: k, bubbles: true, cancelable: true }));
const val = name => { const c = $(`input[name=${name}]:checked`); return c && c.value; };
let changes = 0; $('#root').addEventListener('change', () => changes++);
key('b'); ok(val('q1') === 'y' && changes === 1, 'phím B → chọn đáp án 2 câu chưa làm đầu tiên (bắn change)');
key('3'); ok(val('q2') === 'z', 'sau khi chọn tự sang câu tiếp: phím 3 → câu 2 đáp án 3');
key('A', $('#gap')); ok(val('q1') === 'y' && val('q2') === 'z', 'đang gõ trong ô điền → không bắt phím');
key('e'); ok(val('q2') === 'z', 'phím ngoài số đáp án → bỏ qua');
$('input[name=q1][value=x]').focus(); key('d'); ok(val('q1') === 'w', 'câu đang focus được ưu tiên');
const lab = $('input[name=q2][value=x]').closest('label');
lab.dispatchEvent(new w.MouseEvent('contextmenu', { bubbles: true, cancelable: true }));
ok(lab.classList.contains('struck'), 'chuột phải → gạch đáp án');
draw(); await new Promise(r => setTimeout(r, 0));
ok($('input[name=q2][value=x]').closest('label').classList.contains('struck'), 'vẽ lại câu hỏi → vẫn giữ gạch');
ok(JSON.parse(w.sessionStorage.getItem('ck:t1')).q2.includes('x'), 'lưu gạch theo lượt thi (sessionStorage)');
$('input[name=q2][value=x]').focus(); key('1'); ok(val('q2') === 'x' && !$('input[name=q2][value=x]').closest('label').classList.contains('struck'), 'chọn đáp án đã gạch → bỏ gạch');
ok(w.ChoiceKit.attach($('#root')) === kit, 'gắn 2 lần → dùng lại, không nhân đôi');
w.ChoiceKit.split($('#b'), $('#a'), 'sp');
const bar = $('.ck-split');
ok(bar && bar.getAttribute('role') === 'separator' && $('#b').style.gridTemplateColumns.includes('50fr'), 'chia cột: thanh separator, mặc định 50/50');
bar.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
ok(bar.getAttribute('aria-valuenow') === '55' && w.localStorage.getItem('sp') === '55', 'phím → nới cột 5 % và nhớ tỉ lệ');
for (let i = 0; i < 10; i++) bar.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
ok(bar.getAttribute('aria-valuenow') === '75', 'giới hạn 25–75 %');
$('#root').remove(); key('a'); ok(!$('#root'), 'gỡ màn → tự tháo bộ bắt phím (không lỗi)');
if (fails) { console.log(`✗ choice-kit: ${fails}/${n} lỗi`); process.exit(1); }
console.log(`✓ choice-kit: ${n} kiểm (phím A–D/1–4, bỏ qua khi gõ, gạch đáp án + nhớ, chia cột)`);
